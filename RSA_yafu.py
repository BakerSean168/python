from Crypto.Util.number import long_to_bytes, inverse

# 给定的 n 和 c
n = 15241208217768849887180010139590210767831431018204645415681695749294131435566140166245881287131522331092026252879324931622292179726764214435307
c = 12608550100856399369399391849907846147170257754920996952259023159548789970041433744454761458030776176806265496305629236559551086998780836655717
e = 65537

# 分解 n 得到的素数因子
factors = [
    2201440207
    , 3354884521
    , 4171911923
    , 2719600579
    , 2767137487
    , 2585574697
    , 3989697563
    , 4044505687
    , 4021078331
    , 2151018733
    , 2906576131
    , 2315495107
    , 2923522073
    , 2758708999
    , 3355651511
]

# 计算 phi(n)
phi_n = 1
for p in factors:
    phi_n *= (p - 1)

# 计算私钥 d
d = inverse(e, phi_n)

# 解密密文 c
m = pow(c, d, n)

# 将明文 m 转换回字节串 flag
flag = long_to_bytes(m)
print(flag.decode())